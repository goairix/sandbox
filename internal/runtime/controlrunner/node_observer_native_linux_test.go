func TestNodeObserverPhysicalNativeChild(t *testing.T) {
	path := os.Getenv("SANDBOX_NODE_OBSERVER_CHILD_SETUP")
	if path == "" {
		return
	}
	require.Equal(t, 1, os.Getpid())
	var setup observerNativeSetup
	wire, err := os.ReadFile(path)
	require.NoError(t, err)
	require.NoError(t, json.Unmarshal(wire, &setup))
	// Change only this freshly cloned private mount namespace. Remove the
	// fixture's extra writable view before dropping setup capabilities forever.
	require.NoError(t, unix.Mount("", "/", "", unix.MS_PRIVATE|unix.MS_REC, ""))
	require.NoError(t, unix.Unmount(setup.WritableMount, 0))
	// Detach only the inherited private proc view (and its Docker masking
	// submounts), so the genuine PID1 seal sees exactly one new proc mount.
	require.NoError(t, unix.Unmount("/proc", unix.MNT_DETACH))
	require.NoError(t, unix.Mount("proc", "/proc", "proc", unix.MS_NOSUID|unix.MS_NODEV|unix.MS_NOEXEC, ""))
	for _, cap := range []uintptr{unix.CAP_SYS_ADMIN, unix.CAP_SYS_PTRACE} {
		_, _, errno := syscall.AllThreadsSyscall6(unix.SYS_PRCTL, unix.PR_CAPBSET_DROP, cap, 0, 0, 0, 0)
		require.Zero(t, errno)
	}
	header := &unix.CapUserHeader{Version: unix.LINUX_CAPABILITY_VERSION_3}
	data := &[2]unix.CapUserData{{Permitted: 0x1e0, Effective: 0x1e0}}
	_, _, errno := syscall.AllThreadsSyscall(unix.SYS_CAPSET, uintptr(unsafe.Pointer(header)), uintptr(unsafe.Pointer(data)), 0)
	runtime.KeepAlive(header)
	runtime.KeepAlive(data)
	require.Zero(t, errno)
	status, err := os.ReadFile("/proc/self/status")
	require.NoError(t, err)
	for _, line := range strings.Split(string(status), "\n") {
		if strings.HasPrefix(line, "Cap") || strings.HasPrefix(line, "NoNewPrivs:") || strings.HasPrefix(line, "Seccomp:") {
			t.Log("actual pre-Bootstrap " + line)
		}
	}
	kernel, err := launcher.BootstrapPID1()
	require.NoError(t, err)
	require.NoError(t, kernel.ValidateCurrent())
	verifier, err := p.NewManagementVerifier(setup.Binding, []ed25519.PublicKey{setup.Root})
	require.NoError(t, err)
	s, err := NewSupervisor(SupervisorOptions{Kernel: kernel, UID: 1000, GID: 1000, ContractDigest: setup.Contract, Verifier: verifier, Clock: nativeFixtureClock{}, JournalDirectory: filepath.Join(filepath.Dir(path), "supervisor-journal"), Executable: os.Args[0]})
	require.NoError(t, err)
	defer s.Close()
	conn, err := net.DialUnix("unix", nil, &net.UnixAddr{Name: setup.Socket, Net: "unix"})
	require.NoError(t, err)
	defer conn.Close()
	require.NoError(t, conn.SetDeadline(time.Now().Add(15*time.Second)))
	require.NoError(t, ct.WriteNodeObserverFrame(conn, observerNativeJSON(t, s.Birth())))
	wire, err = ct.ReadNodeObserverFrame(conn)
	require.NoError(t, err)
	request, err := p.DecodeNodeEnrollmentRequest(wire)
	require.NoError(t, err)
	activation, err := verifier.VerifyTargetActivation(request.Activation, request.RuntimeCertificate, request.IssuerCertificate, s.Birth(), time.Now().UTC())
	require.NoError(t, err)
	// Enrollment occurs before admission. The real activation is installed only
	// after the external observer has durably retained the kernel anchors.
	peer, err := net.DialUnix("unix", nil, &net.UnixAddr{Name: filepath.Join(filepath.Dir(path), "enroll.sock"), Net: "unix"})
	require.NoError(t, err)
	session, challenge, err := ct.OpenNodeEnrollment(context.Background(), peer, request)
	require.NoError(t, err)
	defer session.Close()
	_, err = verifier.VerifyNodeObserverCertificate(challenge.ObserverCertificate, challenge.NodeUID, challenge.NodeBootID, time.Now().UTC())
	require.NoError(t, err)
	require.Equal(t, activation.Identity().Runtime, challenge.Runtime)
	signed, err := p.NodeEnrollmentChallengeSigningBytes(challenge)
	require.NoError(t, err)
	receipt, err := session.Enroll(context.Background(), p.NodeEnrollmentResponse{Version: 1, Purpose: "runtime_node_enrollment_response", Signature: ed25519.Sign(s.key, signed)})
	require.NoError(t, err)
	require.NoError(t, s.Activate(context.Background(), activation))
	user := exec.Command("/bin/sleep", "600")
	user.SysProcAttr = &syscall.SysProcAttr{Credential: &syscall.Credential{Uid: 1000, Gid: 1000, NoSetGroups: true}}
	require.NoError(t, user.Start())
	require.NoError(t, ct.WriteNodeObserverFrame(conn, receipt.Wire()))
	t.Logf("real Supervisor namespacePID=%d birthBoot=%s descendantPID=%d; runtime private key remains in Supervisor", os.Getpid(), s.Birth().BootID, user.Process.Pid)
	// No voluntary success: the producer must kill this genuine PID1 and its
	// real descendant. Its original parent Cmd.Wait is checked outside this PIDNS.
	_ = user.Wait()
	t.Fatal("descendant exited before external observer SIGKILL")
}

func observerNativeRecord(t *testing.T, names string, values ...any) []byte {
	t.Helper()
	keys := strings.Split(names, ",")
	require.Len(t, values, len(keys))
	var wire bytes.Buffer
	wire.WriteByte('{')
	for i, key := range keys {
		if i > 0 {
			wire.WriteByte(',')
		}
		wire.Write(observerNativeJSON(t, key))
		wire.WriteByte(':')
		wire.Write(observerNativeJSON(t, values[i]))
	}
	wire.WriteByte('}')
	return wire.Bytes()
}

func observerNativeEtcd(t *testing.T, dir string) (*clientv3.Client, *tls.Config, uint64) {
	t.Helper()
	pub, caKey, err := ed25519.GenerateKey(rand.Reader)
	require.NoError(t, err)
	now := time.Now()
	ca := &x509.Certificate{SerialNumber: big.NewInt(1), Subject: pkix.Name{CommonName: "observer-fixture-ca"}, NotBefore: now.Add(-time.Hour), NotAfter: now.Add(time.Hour), IsCA: true, BasicConstraintsValid: true, KeyUsage: x509.KeyUsageCertSign}
	caDER, err := x509.CreateCertificate(rand.Reader, ca, ca, pub, caKey)
	require.NoError(t, err)
	pool := x509.NewCertPool()
	require.True(t, pool.AppendCertsFromPEM(pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: caDER})))
	issue := func(name string, serial int64, server bool) tls.Certificate {
		public, key, err := ed25519.GenerateKey(rand.Reader)
		require.NoError(t, err)
		leaf := &x509.Certificate{SerialNumber: big.NewInt(serial), Subject: pkix.Name{CommonName: name}, NotBefore: now.Add(-time.Hour), NotAfter: now.Add(time.Hour), KeyUsage: x509.KeyUsageDigitalSignature, ExtKeyUsage: []x509.ExtKeyUsage{x509.ExtKeyUsageClientAuth}}
		if server {
			leaf.ExtKeyUsage = []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth, x509.ExtKeyUsageClientAuth}
			leaf.IPAddresses = []net.IP{net.ParseIP("127.0.0.1")}
		}
		der, err := x509.CreateCertificate(rand.Reader, leaf, ca, public, caKey)
		require.NoError(t, err)
		return tls.Certificate{Certificate: [][]byte{der}, PrivateKey: key}
	}
	server, root, observer := issue("server", 2, true), issue("root", 3, false), issue("node-observer", 4, false)
	write := func(name string, data []byte) string {
		path := filepath.Join(dir, name)
		require.NoError(t, os.WriteFile(path, data, 0600))
		return path
	}
	caPath := write("ca.pem", pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: caDER}))
	certPath := write("server.pem", pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: server.Certificate[0]}))
	keyDER, err := x509.MarshalPKCS8PrivateKey(server.PrivateKey)
	require.NoError(t, err)
	keyPath := write("server-key.pem", pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: keyDER}))
	cmd := exec.Command("/fixture/etcd", "--name=observer", "--data-dir="+filepath.Join(dir, "etcd"), "--listen-client-urls=https://127.0.0.1:2379", "--advertise-client-urls=https://127.0.0.1:2379", "--listen-peer-urls=http://127.0.0.1:2380", "--initial-advertise-peer-urls=http://127.0.0.1:2380", "--initial-cluster=observer=http://127.0.0.1:2380", "--cert-file="+certPath, "--key-file="+keyPath, "--trusted-ca-file="+caPath, "--client-cert-auth=true", "--log-level=warn", "--max-txn-ops=64", "--quota-backend-bytes=67108864")
	cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
	require.NoError(t, cmd.Start())
	t.Cleanup(func() {
		_ = cmd.Process.Signal(syscall.SIGTERM)
		err := cmd.Wait()
		t.Logf("original TLS etcd Cmd.Wait=%v", err)
		if err != nil {
			var exited *exec.ExitError
			require.True(t, errors.As(err, &exited))
			require.Equal(t, syscall.SIGTERM, exited.Sys().(syscall.WaitStatus).Signal())
		}
	})
	adminTLS := &tls.Config{MinVersion: tls.VersionTLS13, RootCAs: pool, Certificates: []tls.Certificate{root}}
	admin, err := clientv3.New(clientv3.Config{Endpoints: []string{"https://127.0.0.1:2379"}, TLS: adminTLS, DialTimeout: 2 * time.Second})
	require.NoError(t, err)
	t.Cleanup(func() { require.NoError(t, admin.Close()) })
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	var status *clientv3.StatusResponse
	for ctx.Err() == nil {
		status, err = admin.Status(ctx, "https://127.0.0.1:2379")
		if err == nil {
			break
		}
		time.Sleep(20 * time.Millisecond)
	}
	require.NoError(t, err)
	_, err = admin.UserAddWithOptions(ctx, "root", "", &clientv3.UserAddOptions{NoPassword: true})
	require.NoError(t, err)
	_, err = admin.UserGrantRole(ctx, "root", "root")
	require.NoError(t, err)
	_, err = admin.UserAddWithOptions(ctx, "node-observer", "", &clientv3.UserAddOptions{NoPassword: true})
	require.NoError(t, err)
	_, err = admin.RoleAdd(ctx, "observer-read")
	require.NoError(t, err)
	_, err = admin.RoleGrantPermission(ctx, "observer-read", "/sandbox/observer/v1/", clientv3.GetPrefixRangeEnd("/sandbox/observer/v1/"), clientv3.PermissionType(clientv3.PermRead))
	require.NoError(t, err)
	_, err = admin.UserGrantRole(ctx, "node-observer", "observer-read")
	require.NoError(t, err)
	_, err = admin.AuthEnable(ctx)
	require.NoError(t, err)
	return admin, &tls.Config{MinVersion: tls.VersionTLS13, RootCAs: pool, Certificates: []tls.Certificate{observer}}, status.Header.ClusterId
}

